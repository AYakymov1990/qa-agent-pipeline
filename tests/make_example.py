#!/usr/bin/env python3
"""Синтетичний чек-лист у форматі AvtoPro (лист «Check-list» + «Анализ PBI») для самоперевірки скриптів.
Дані вигадані; структура — як у реальних чек-листах: P1/P2/P3 у кожному рядку «Примечание»."""
import sys
from pathlib import Path
import openpyxl
from openpyxl.worksheet.datavalidation import DataValidation

out = Path(sys.argv[1] if len(sys.argv) > 1 else 'examples/checklist-example.xlsx')
wb = openpyxl.Workbook()
ws = wb.active
ws.title = 'Check-list'
ws.append(['Проверка', 'Ожидаемый результат', 'Прогон 1', 'Прогон 2', 'Примечание', 'ID'])
rows = [
    ('Чекаут ES, гость: открыть форму с IP ES', 'В País выбрана España.', 'P1 · Данные: ES, гость; продавец с Genei; IP ES · Источник: Описание', 'CHK-001'),
    ('Чекаут ES, гость: нажать оплату с пустым País', 'В форме показана ошибка «País»; заказ не создан.', 'P1 · Только тест-среда · Данные: ES, гость с IP UA · Источник: Описание', 'CHK-002'),
    ('Чекаут ES: отправить форму с пустым индексом', 'Под индексом показано «Indique el código postal».', 'P2 · Только тест-среда · Данные: ES, покупатель · Источник: Описание', 'CHK-003'),
    ('Чекаут ES: открыть контактную форму на телефоне', 'Визуальный порядок полей: имя, фамилия, CIF.', 'P2 · Данные: ES, покупатель; экран телефона · Источник: Описание', 'CHK-004'),
    ('Чекаут ES: изменить Nombre после выбора адреса', 'По допущению Q-01: выбор сохранённого адреса сброшен.', 'P2 · Данные: ES, покупатель с адресами · Источник: Описание · Пока считаем: Q-01', 'CHK-005'),
    ('Чекаут ES: ввести пятизначный несуществующий индекс', 'Под индексом показано «Este código postal no existe. Compruébelo».', 'P3 · Данные: ES, покупатель · Источник: Описание', 'CHK-006'),
    ('[Регресс] Чекаут PL: открыть подсказку у стоимости доставки', 'Значок «?» и прежний тултип доступны.', 'P2 · Данные: PL, покупатель · Источник: RegressionList', 'CHK-007'),
    ('Чекаут ES: выбрать адрес другой страны', 'В сводке выбран маршрут доставки страны нового адреса.', 'P1 · Предусловие: QA заранее сопоставил тарифы. · Данные: ES, дропшиппер · Источник: Описание', 'CHK-008'),
]
for r in rows:
    ws.append([r[0], r[1], None, None, r[2], r[3]])
ws['H2'], ws['I2'] = 'PBI:', '=HYPERLINK("https://dev.azure.com/abp/Avto.Pro/_workitems/edit/1","1 Пример задачи")'
dv = DataValidation(type='list', formula1='"Успешно,Баг,Пропущено"')
dv.add(f'C2:D{len(rows) + 1}')
ws.add_data_validation(dv)
a = wb.create_sheet('Анализ PBI')
a.append(['Анализ PBI', 'Вопрос на уточнение', 'Тип вопроса', None, 'Тип PBI:', 'Изменение бизнес-логики — пример'])
a.append(['Q-01. Правило сброса адреса расходится с PR.', 'Dev: Намеренно ли …?', 'Противоречие'])
a.append(['Источник не прочитан: FIGMA — пример', None, 'Служебное'])
out.parent.mkdir(parents=True, exist_ok=True)
wb.save(out)
print(out)
